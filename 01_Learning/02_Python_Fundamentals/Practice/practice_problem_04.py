''' Q4: Typecasting Practice
 You are given a string:

 num = "45"

 Convert it into an integer
 Add 10 to it
 Print the result
 '''

# Solution: 

num = "45"

# Method 1: Convert the string into an integer
a = int(num)
a += 10

print(a)


# Method 2: Typecast and add 10 directly
print(int(num) + 10)

